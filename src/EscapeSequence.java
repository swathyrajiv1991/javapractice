
public class EscapeSequence {
	public static void main(String args[]) {
	        // Demonstrate various escape sequences in meaningful sentences
	        

	        System.out.println("\n---- RECEIPT ----");

	        // Print a formatted receipt-style output using tabs
	        // Note: The number of tabs (\\t) is adjusted to align prices given the different item name lengths.
	        System.out.println("Item\t\t\tPrice");
	        System.out.println("Coffee\t\t\tRs. 50");
	        System.out.println("Sandwich\t\tRs. 120");
	        System.out.println("Soda\t\t\tRs. 40");
	        System.out.println("Total\t\t\tRs. 210");
	    
	}
}
